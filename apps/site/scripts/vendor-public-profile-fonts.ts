/**
 * Regenerates `src/lib/server/public-profile-fonts.ts`, the OFL fonts embedded
 * in the standalone public résumé document so the headless Chromium in the
 * production image (which has no web fonts) prints the same faces as the site.
 *
 * Latin subsets of the Google Fonts builds the site already loads in
 * `src/app.html`.  Both families are licensed under the SIL Open Font License
 * 1.1, which permits embedding and bundling; see `public-profile-fonts.ts`.
 *
 *   pnpm --filter @willgriffin/iolaus-site exec tsx scripts/vendor-public-profile-fonts.ts
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

interface VendoredFace {
  family: string;
  style: 'normal' | 'italic';
  /** A single weight, or the range a variable slice covers. */
  weight: string;
  url: string;
}

// Pinned gstatic URLs (latin subset) as served for the families in app.html.
// Google serves one variable slice for every weight of a variable family, so
// the regular and semibold requests resolve to the same file.
const FACES: VendoredFace[] = [
  {
    family: 'Source Serif 4',
    style: 'normal',
    weight: '400 600',
    url: 'https://fonts.gstatic.com/s/sourceserif4/v15/vEFF2_tTDB4M7-auWDN0ahZJW3IX2ih5nk3AucvUHf6kDXr4Y3qwzQ.woff2',
  },
  {
    family: 'Source Serif 4',
    style: 'italic',
    weight: '400',
    url: 'https://fonts.gstatic.com/s/sourceserif4/v15/vEF02_tTDB4M7-auWDN0ahZJW1ge6NmXpVAHV83Bfb_US2D2QYxoUKIkn98pRl9tDMQCjDDUXmAz.woff2',
  },
  {
    family: 'Inter Tight',
    style: 'normal',
    weight: '500 600',
    url: 'https://fonts.gstatic.com/s/intertight/v9/NGSwv5HMAFg6IuGlBNMjxLsH8ahuQ2e8.woff2',
  },
];

async function fetchFace(face: VendoredFace): Promise<string> {
  const response = await fetch(face.url);
  if (!response.ok)
    throw new Error(`${face.family} ${face.weight}: HTTP ${response.status}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.length < 1_000 || String.fromCharCode(...bytes.slice(0, 4)) !== 'wOF2')
    throw new Error(`${face.family} ${face.weight}: not a WOFF2 file`);
  return Buffer.from(bytes).toString('base64');
}

const faces = await Promise.all(
  FACES.map(async (face) => ({ ...face, data: await fetchFace(face) })),
);

const entries = faces
  .map(
    (face) => `  {
    family: '${face.family}',
    style: '${face.style}',
    weight: '${face.weight}',
    data: '${face.data}',
  },`,
  )
  .join('\n');

const source = `// Generated by scripts/vendor-public-profile-fonts.ts — do not edit by hand.
//
// Latin subsets of Source Serif 4 (© 2014–2023 Adobe, designed by Frank
// Grießhammer) and Inter Tight (© 2016 The Inter Project Authors, designed by
// Rasmus Andersson), both licensed under the SIL Open Font License, Version
// 1.1 (https://openfontlicense.org).  The OFL permits embedding the fonts in
// documents and bundling them with software; the fonts may not be sold by
// themselves.  Full license text: ./public-profile-fonts.OFL.txt

/** One embeddable face: a base64 WOFF2 latin subset. */
export interface PublicProfileFontFace {
  family: string;
  style: 'normal' | 'italic';
  /** A single weight, or the range a variable slice covers. */
  weight: string;
  data: string;
}

export const PUBLIC_PROFILE_FONT_FACES: readonly PublicProfileFontFace[] = [
${entries}
];
`;

const target = fileURLToPath(
  new URL('../src/lib/server/public-profile-fonts.ts', import.meta.url),
);
await writeFile(target, source);
console.log(
  `wrote ${target} (${faces.map((face) => `${face.family} ${face.style} ${face.weight}`).join(', ')})`,
);
